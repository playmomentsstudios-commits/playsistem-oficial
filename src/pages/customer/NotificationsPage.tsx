import {useCallback,useEffect,useRef,useState} from 'react'
import {Link,useLocation,useNavigate} from 'react-router-dom'
import {portalApi} from '../../api/portal'
import {LoadingState} from '../../components/ui/AsyncState'
import {CompactPageHeader} from '../../components/ui/CompactWorkspace'

type Notice={
  id:string
  type:string
  title:string
  message:string
  link:string|null
  created_at:string
  read_at:string|null
}

type Filter='all'|'unread'

function noticeCategory(type:string){
  if(type.startsWith('project_'))return 'Projetos e tarefas'
  if(type.startsWith('file_'))return 'Arquivos e aprovações'
  if(type.includes('payment')||type.includes('order')||type.includes('quote'))return 'Pedidos e pagamentos'
  if(type.includes('message')||type.includes('chat'))return 'Mensagens'
  return 'Atualização'
}

function safeDestination(link:string|null,origin:string){
  // Links generated by internal notifications are routes, not outside URLs.
  // Never let a stored notice navigate the user to an untrusted website.
  return link&&/^\/(?:app|admin)\/[a-z0-9/_-]+(?:\?[a-z0-9=&_-]+)?$/i.test(link)
    ?link:origin
}

export function NotificationsPage(){
  const navigate=useNavigate()
  const {pathname}=useLocation()
  const admin=pathname.startsWith('/admin/')
  const listPath=admin?'/admin/notificacoes':'/app/notificacoes'
  const settingsPath=admin?'/admin/configuracoes':'/app/configuracoes#notificacoes'
  const [rows,setRows]=useState<Notice[]>([])
  const [loading,setLoading]=useState(true)
  const [refreshing,setRefreshing]=useState(false)
  const [busy,setBusy]=useState(false)
  const [error,setError]=useState('')
  const [filter,setFilter]=useState<Filter>('all')
  const active=useRef(false)

  const load=useCallback(async(showIndicator=false)=>{
    if(showIndicator)setRefreshing(true)
    try{
      // Rental events are genuine operational events, not fabricated previews.
      await portalApi.syncMyRentalNotifications().catch(()=>0)
      const result=await portalApi.notifications()
      if(active.current){setRows(result as Notice[]);setError('')}
    }catch(cause){
      if(active.current)setError(cause instanceof Error?cause.message:'Não foi possível carregar suas notificações.')
    }finally{
      if(active.current){setLoading(false);setRefreshing(false)}
    }
  },[])

  useEffect(()=>{
    active.current=true
    void load()
    const poll=window.setInterval(()=>{if(document.visibilityState==='visible')void load()},15000)
    const refresh=()=>void load()
    window.addEventListener('focus',refresh)
    document.addEventListener('visibilitychange',refresh)
    return()=>{
      active.current=false
      window.clearInterval(poll)
      window.removeEventListener('focus',refresh)
      document.removeEventListener('visibilitychange',refresh)
    }
  },[load])

  const unread=rows.filter(row=>!row.read_at).length
  const visible=filter==='unread'?rows.filter(row=>!row.read_at):rows
  const markAll=async()=>{
    if(busy||unread===0)return
    setBusy(true)
    try{
      await portalApi.markAllNotifications()
      setRows(current=>current.map(row=>({...row,read_at:row.read_at||new Date().toISOString()})))
      setError('')
    }catch(cause){
      setError(cause instanceof Error?cause.message:'Não foi possível marcar os avisos como lidos.')
    }finally{setBusy(false)}
  }
  const openNotice=async(row:Notice)=>{
    const destination=safeDestination(row.link,listPath)
    if(!row.read_at){
      try{
        await portalApi.markNotification(row.id)
        setRows(current=>current.map(item=>item.id===row.id?{...item,read_at:new Date().toISOString()}:item))
      }catch{
        // Still let the customer open an existing project or task; a read-marker
        // failure must not block the actual notice destination.
      }
    }
    if(destination!==listPath)navigate(destination)
  }

  return <div className="space-y-3 pb-6">
    <CompactPageHeader eyebrow="Minha conta" title="Notificações"
      description={loading?'Carregando avisos...':unread?unread+' aviso(s) não lido(s)':'Acompanhe as novidades dos seus projetos e serviços.'}
      actions={<div className="flex items-center gap-2">
        <button type="button" title="Atualizar notificações" aria-label="Atualizar notificações" disabled={refreshing}
          onClick={()=>void load(true)}
          className="inline-flex min-h-10 min-w-10 items-center justify-center rounded-xl border border-white/10 text-gray-300 hover:bg-white/[.06] disabled:opacity-50">
          <svg aria-hidden="true" width="17" height="17" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.8" strokeLinecap="round"><path d="M20 11a8 8 0 1 0-2 6"/><path d="M20 4v7h-7"/></svg>
        </button>
        <Link to={settingsPath} aria-label="Configurações de notificações" title="Configurações de notificações"
          className="inline-flex min-h-10 min-w-10 items-center justify-center rounded-xl border border-white/10 text-gray-300 hover:border-[#A65A2A]/35 hover:text-[#DFA269]">
          <svg aria-hidden="true" width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="1.8" strokeLinecap="round" strokeLinejoin="round"><circle cx="12" cy="12" r="3"/><path d="M19 12a7 7 0 0 0-.1-1l2-1.5-2-3.5-2.4 1a7 7 0 0 0-1.8-1L14.5 3h-5l-.3 3a7 7 0 0 0-1.8 1L5 6 3 9.5 5.1 11a7 7 0 0 0 0 2L3 14.5 5 18l2.4-1a7 7 0 0 0 1.8 1l.3 3h5l.3-3a7 7 0 0 0 1.8-1l2.4 1 2-3.5-2.1-1.5c.1-.3.1-.7.1-1Z"/></svg>
        </Link>
      </div>}/>

    {error&&<p role="alert" className="rounded-xl border border-amber-500/20 bg-amber-500/[.06] p-3 text-xs text-amber-200">{error} <button type="button" onClick={()=>void load(true)} className="ml-2 underline">Tentar novamente</button></p>}
    <div className="flex flex-wrap items-center justify-between gap-2 rounded-xl border border-white/10 bg-white/[.025] p-2">
      <div role="group" aria-label="Filtrar notificações" className="flex items-center gap-1">
        <button type="button" aria-pressed={filter==='all'} onClick={()=>setFilter('all')}
          className={'min-h-10 rounded-lg px-3 text-xs font-semibold '+(filter==='all'?'bg-[#A65A2A]/15 text-[#DFA269]':'text-gray-400 hover:bg-white/[.05]')}>Todas ({rows.length})</button>
        <button type="button" aria-pressed={filter==='unread'} onClick={()=>setFilter('unread')}
          className={'min-h-10 rounded-lg px-3 text-xs font-semibold '+(filter==='unread'?'bg-[#A65A2A]/15 text-[#DFA269]':'text-gray-400 hover:bg-white/[.05]')}>Não lidas ({unread})</button>
      </div>
      {unread>0&&<button type="button" disabled={busy} onClick={()=>void markAll()}
        className="min-h-10 rounded-lg px-3 text-xs font-semibold text-[#DFA269] hover:bg-white/[.05] disabled:opacity-50">Marcar todas como lidas</button>}
    </div>

    {loading?<LoadingState/>:visible.length===0?
      <div className="rounded-xl border border-white/10 bg-white/[.025] px-4 py-10 text-center">
        <span aria-hidden="true" className="text-3xl">🔔</span>
        <h2 className="mt-3 text-sm font-semibold text-white">{filter==='unread'?'Nenhuma notificação pendente':'Nenhuma notificação recebida'}</h2>
        <p className="mx-auto mt-2 max-w-md text-xs leading-5 text-gray-400">{filter==='unread'?'Os avisos recebidos estão marcados como lidos.':'Quando houver atualizações reais sobre projetos, tarefas, arquivos, pedidos ou pagamentos, os avisos aparecerão aqui.'}</p>
        {filter==='unread'&&rows.length>0&&<button type="button" onClick={()=>setFilter('all')} className="mt-3 min-h-10 text-xs font-semibold text-[#DFA269]">Ver todas as notificações</button>}
      </div>:
      <div className="space-y-2" aria-label="Notificações recebidas">
        {visible.map(row=><button key={row.id} type="button" onClick={()=>void openNotice(row)}
          className={'flex w-full items-start gap-3 rounded-xl border p-3 text-left transition-colors sm:p-4 '+(row.read_at?'border-white/[.07] bg-white/[.025] hover:bg-white/[.045]':'border-[#A65A2A]/25 bg-[#A65A2A]/[.07] hover:bg-[#A65A2A]/[.11]')}>
          <span aria-hidden="true" className={'mt-0.5 flex h-9 w-9 shrink-0 items-center justify-center rounded-lg text-lg '+(row.read_at?'bg-white/[.045]':'bg-[#A65A2A]/15')}>🔔</span>
          <span className="min-w-0 flex-1">
            <span className="flex flex-wrap items-center gap-x-2 gap-y-1">
              <span className={'text-sm '+(row.read_at?'font-medium text-gray-200':'font-semibold text-white')}>{row.title}</span>
              {!row.read_at&&<span className="rounded-full bg-[#A65A2A]/15 px-2 py-0.5 text-[10px] font-semibold text-[#DFA269]">Novo</span>}
            </span>
            <span className="mt-1 block whitespace-pre-line text-xs leading-5 text-gray-400">{row.message}</span>
            <span className="mt-2 flex flex-wrap items-center gap-2 text-[11px] text-gray-500">
              <span>{noticeCategory(row.type)}</span><span aria-hidden="true">·</span>
              <time dateTime={row.created_at}>{new Date(row.created_at).toLocaleString('pt-BR')}</time>
              {safeDestination(row.link,listPath)!==listPath&&<span className="font-semibold text-[#DFA269]">Ver detalhes ↗</span>}
            </span>
          </span>
          {!row.read_at&&<span className="mt-2 h-2 w-2 shrink-0 rounded-full bg-[#DFA269]" aria-label="Não lida"/>}
        </button>)}
      </div>
    }

    {!admin&&<div className="flex flex-wrap items-center justify-between gap-2 border-t border-white/[.06] pt-3 text-xs text-gray-500">
      <span>Push e WhatsApp são canais opcionais. As notificações desta página vêm do seu portal.</span>
      <Link to="/app/configuracoes#whatsapp" className="inline-flex min-h-10 items-center text-xs font-semibold text-[#DFA269] hover:underline">Configurar WhatsApp ↗</Link>
    </div>}
  </div>
}
