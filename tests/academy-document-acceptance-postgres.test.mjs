import test from 'node:test'
import assert from 'node:assert/strict'
import { PGlite } from '@electric-sql/pglite'
import { readFile } from 'node:fs/promises'

const migration = await readFile(
  new URL('../supabase/migrations/20261011050200_secure_academy_document_acceptance.sql', import.meta.url),
  'utf8',
)

test('academy document acceptance preserves student and active-admin flows while denying anon and other users', async () => {
  const db = new PGlite()
  const student = '10000000-0000-4000-8000-000000000001'
  const other = '10000000-0000-4000-8000-000000000002'
  const admin = '10000000-0000-4000-8000-000000000003'
  const inactiveAdmin = '10000000-0000-4000-8000-000000000004'
  const document = '20000000-0000-4000-8000-000000000001'
  const otherDocument = '20000000-0000-4000-8000-000000000002'
  const call = id => db.query(
    'select accepted_by,acceptance_type from public.academy_accept_document($1::uuid)',
    [id],
  )
  const withRole = async (role, uid, action) => {
    await db.exec('reset role')
    await db.query("select set_config('request.jwt.claim.sub',$1,false)", [uid || ''])
    await db.exec('set role ' + role)
    try { return await action() } finally { await db.exec('reset role') }
  }
  try {
    await db.exec(`
      create role anon nologin;
      create role authenticated nologin;
      create role service_role nologin;
      create schema auth;
      create function auth.uid() returns uuid language sql stable as
        $$ select nullif(current_setting('request.jwt.claim.sub',true),'')::uuid $$;
      create table public.profiles(id uuid primary key, role text, status text not null);
      create function public.is_active_admin() returns boolean language sql stable security definer
        set search_path=public as
        $$ select exists(select 1 from public.profiles where id=auth.uid() and role='admin' and status='active') $$;
      create table public.academy_students(id uuid primary key, profile_id uuid);
      create table public.academy_documents(
        id uuid primary key, status text not null, current_version integer not null,
        student_id uuid not null, enrollment_id uuid, file_hash text,
        document_type text not null, title text not null, updated_at timestamptz
      );
      create table public.academy_document_acceptances(
        id bigint generated by default as identity primary key,
        document_id uuid not null, document_version integer not null,
        student_id uuid not null, enrollment_id uuid, accepted_by uuid not null,
        acceptance_type text not null, document_hash text, evidence jsonb not null,
        accepted_at timestamptz not null default now(),
        revoked_at timestamptz, revoked_by uuid, revoke_reason text,
        unique(document_id,document_version,accepted_by)
      );
      create function public.academy_accept_document(uuid)
        returns public.academy_document_acceptances language sql
        as $$ select null::public.academy_document_acceptances $$;
      grant execute on function public.academy_accept_document(uuid) to public, anon, authenticated, service_role;
      insert into public.profiles values
        ('${admin}','admin','active'),('${inactiveAdmin}','admin','inactive');
      insert into public.academy_students values
        ('${student}','${student}'),('${other}','${other}');
      insert into public.academy_documents values
        ('${document}','issued',1,'${student}',null,'hash-1','consent','Consent',now()),
        ('${otherDocument}','issued',1,'${other}',null,'hash-2','consent','Consent',now());
    `)
    await db.exec(migration)
    const anonExecute = (await db.query(
      "select has_function_privilege('anon','public.academy_accept_document(uuid)','execute') as allowed",
    )).rows[0].allowed
    assert.equal(anonExecute, false)
    await withRole('authenticated', null, async () =>
      assert.rejects(call(document), error => error.code === '42501'))
    await withRole('authenticated', other, async () =>
      assert.rejects(call(document), error => error.code === '42501'))
    await withRole('authenticated', inactiveAdmin, async () =>
      assert.rejects(call(otherDocument), error => error.code === '42501'))

    const own = await withRole('authenticated', student, () => call(document))
    assert.deepEqual(own.rows[0], { accepted_by: student, acceptance_type: 'electronic' })
    assert.equal((await db.query('select status from public.academy_documents where id=$1::uuid', [document])).rows[0].status, 'signed')

    const adminAcceptance = await withRole('authenticated', admin, () => call(otherDocument))
    assert.deepEqual(adminAcceptance.rows[0], { accepted_by: other, acceptance_type: 'admin_recorded' })
  } finally {
    await db.close()
  }
})
