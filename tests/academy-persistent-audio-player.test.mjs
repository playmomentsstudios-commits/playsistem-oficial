import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const source=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const provider=source('src/contexts/AcademyAudioContext.tsx')
const dock=source('src/components/academy/AcademyAudioDock.tsx')
const css=source('src/components/academy/academyAudio.css')
const standalone=source('src/academy/standalone.tsx')
const mainApp=source('src/AppV2.tsx')
const reader=source('src/pages/customer/AcademyLibraryItemPage.tsx')
const captions=source('src/components/academy/AcademyAudiobookCaptions.tsx')
const libraryApi=source('src/api/academyLibrary.ts')

test('Only one audio element persists above route changes in both apps',()=>{
 assert.match(standalone,/<AcademyAudioProvider><Suspense/)
 assert.match(mainApp,/<AcademyAudioProvider>/)
 assert.match(provider,/<audio ref=\{audioRef\} src=\{source\|\|undefined\}/)
 assert.match(provider,/onLoadedMetadata=\{loaded\}/)
 assert.match(provider,/onTimeUpdate=\{timeUpdate\}/)
 assert.match(provider,/onEnded=\{ended\}/)
 assert.doesNotMatch(reader,/<audio /)
 assert.match(reader,/useAcademyAudio/)
 assert.match(standalone,/playItem\(release\.audiobook!\.id,true\)/)
 assert.match(standalone,/onClick=\{\(\)=>\{void playItem\(item\.id,true\)\}\}/)
})
test('Playlist contains only granted audiobooks and uses authenticated playback tickets',()=>{
 assert.match(provider,/const items=await academyLibraryApi\.mine\(\)/)
 assert.match(provider,/filter\(row=>row\.format==='audiobook'\)/)
 assert.match(provider,/academyLibraryApi\.mediaTicket\(id\)/)
 assert.match(provider,/fetch\(url,\{method:'HEAD',cache:'no-store'\}\)/)
 assert.match(provider,/probe\.status===503/)
 assert.match(provider,/media\.fallbackUrl/)
 assert.match(provider,/if\(!owned\)throw new Error\('Este audiobook não está liberado/)
 assert.match(libraryApi,/academy_my_library/)
 assert.match(libraryApi,/academy-library-media/)
 assert.doesNotMatch(provider,/drive_file_id|source_filename|service_role|localStorage\.setItem\(.*ticket/)
})
test('Leaving a route keeps audio playing, saves position and does not race competing preflights',()=>{
 assert.match(provider,/POSITION_KEY='sagamente\.library\.position\.'/)
 assert.match(provider,/pendingIdRef\.current===id/)
 assert.match(provider,/pendingAutoRef\.current=true/)
 assert.match(provider,/requestRef\.current!==sequence/)
 assert.match(provider,/window\.localStorage\.setItem\(POSITION_KEY\+item\.id/)
 assert.match(provider,/el\.currentTime=Math\.min\(saved/)
 assert.match(provider,/audioRef\.current\?\.pause\(\)/)
 assert.match(provider,/if\(!isAuthenticated\)/)
 assert.match(provider,/session\.metadata=new MediaMetadata/)
})
test('Continuous queue playback, repeat choice, mobile playback restrictions and OS media session',()=>{
 assert.match(provider,/if\(autoplayRef\.current\)shift\(1,true\)/)
 assert.match(provider,/if\(!repeatRef\.current\)return/)
 assert.match(provider,/session\.setActionHandler/)
 for(const action of ['nexttrack','previoustrack','seekbackward','seekforward','seekto','pause','play']){
  assert.match(provider,new RegExp(action))
 }
 assert.match(provider,/O navegador bloqueou o início automático/)
 assert.match(dock,/Reproduzir o próximo automaticamente/)
 assert.match(dock,/Repetir playlist/)
 assert.match(dock,/aria-label="Próximo audiobook"/)
 assert.match(dock,/role="group" aria-label="Playlist dos seus audiobooks"/)
})
test('Swipe mini-player collapses to a touchable edge, without blocking navigation',()=>{
 assert.match(dock,/gestureX/)
 assert.match(dock,/onTouchStart/)
 assert.match(dock,/onTouchEnd/)
 assert.match(dock,/setCollapsed\(true\)/)
 assert.match(dock,/setCollapsed\(false\)/)
 assert.match(dock,/aria-label="Expandir miniplayer do audiobook"/)
 assert.match(dock,/ac-audio-playlist/)
 assert.match(css,/\.ac-audio-dock\.is-collapsed/)
 assert.match(css,/\.ac-audio-edge/)
 assert.match(css,/bottom:calc\(80px \+ env\(safe-area-inset-bottom\)\)/)
 assert.match(css,/\.ac-audio-expanded/)
})
test('Captions track the persistent audio clock and remain tied to the selected audiobook',()=>{
 assert.match(reader,/currentAudio\?<AcademyAudiobookCaptions itemId=\{item\.id\} audioRef=\{audio\.audioRef\}>/)
 assert.match(reader,/Você está ouvindo outro audiobook na playlist/)
 assert.match(captions,/audio\.addEventListener\('timeupdate', update\)/)
 assert.match(captions,/audio\.addEventListener\('seeked', update\)/)
 assert.match(reader,/verifyReaderMedia\(owned\)/)
 assert.match(reader,/<iframe title=/)
})
