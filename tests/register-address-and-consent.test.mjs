import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import test from 'node:test'
const source=(path)=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const form=source('src/pages/public/RegisterPage.tsx')
const helper=source('src/lib/addressLookup.ts')
const auth=source('src/contexts/AuthContext.tsx')
const types=source('src/types/index.ts')

test('searching CEP completes city, state and editable street, with abort support',()=>{
 assert.match(helper,/https:\/\/viacep\.com\.br\/ws\//)
 assert.match(helper,/AbortSignal/)
 assert.match(helper,/data\.uf/)
 assert.match(form,/const address=await lookupCep\(value,controller\.signal\)/)
 assert.match(form,/state:address\.uf,city:address\.localidade/)
 assert.match(form,/street:address\.logradouro\|\|prev\.street/)
 assert.match(form,/setCepStatus\('CEP localizado/)
 assert.match(form,/return \(\)=>\{window\.clearTimeout\(timer\);controller\.abort\(\)\}/)
})
test('state and city can be selected manually; no fake primary CEP is invented',()=>{
 assert.match(form,/handleStateChange/)
 assert.match(form,/handleCityChange/)
 assert.match(form,/Não sei meu CEP/)
 assert.match(form,/unknownCep/)
 assert.match(form,/lookupStreetCeps\(selectedState,selectedCity,selectedStreet,controller\.signal\)/)
 assert.match(form,/list\.length===1/)
 assert.match(form,/Encontramos mais de um CEP/)
 assert.match(form,/Escolha o correspondente/)
 assert.match(form,/Não existe um CEP principal garantido/)
 assert.match(helper,/normalizePlace/)
})
test('address can be submitted without number or unknown CEP but not without full location',()=>{
 assert.match(form,/Sem número \(S\/N\)/)
 assert.match(form,/withoutNumber \? 'S\/N' : form\.addressNumber/)
 assert.match(form,/if \(!unknownCep && form\.postalCode/)
 assert.match(form,/if \(!withoutNumber && !form\.addressNumber\.trim\(\)\)/)
 assert.match(form,/if \(!form\.street\.trim\(\)\)/)
 assert.match(form,/if \(!form\.neighborhood\.trim\(\)\)/)
 assert.match(form,/if \(!form\.city\.trim\(\)\)/)
 assert.match(form,/if \(form\.state\.trim\(\)\.length !== 2\)/)
})
test('terms are required but neither WhatsApp nor marketing preference blocks registration',()=>{
 assert.match(form,/acceptedConditions/)
 assert.match(form,/disabled=\{!acceptedConditions \|\| loading\}/)
 assert.match(form,/checked=\{form\.whatsappUpdatesOptIn\}/)
 assert.match(form,/checked=\{form\.marketingOptIn\}/)
 assert.match(auth,/if \(payload\.acceptedConditions !== true\) throw new Error/)
 assert.match(auth,/signup_conditions_version/)
 assert.match(auth,/signup_conditions_accepted: payload\.acceptedConditions === true/)
 assert.match(types,/acceptedConditions: boolean/)
 assert.doesNotMatch(form,/disabled=\{[^}]*whatsappUpdatesOptIn/)
 assert.doesNotMatch(form,/disabled=\{[^}]*marketingOptIn/)
 assert.match(auth,/supabase\.auth\.signUp\(/)
 assert.match(auth,/emailRedirectTo: siteUrl \+ '\/email-confirmado'/)
})
