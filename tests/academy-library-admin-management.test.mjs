import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import test from 'node:test'
const read=(path)=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const db=read('supabase/migrations/20261015053000_academy_library_admin_management.sql')
const uploader=read('supabase/functions/academy-library-upload/index.ts')
const drive=read('supabase/functions/_shared/googleDrive.ts')
const admin=read('src/components/academy/AdminAcademyLibrary.tsx')
const api=read('src/api/academyLibraryAdmin.ts')
const hub=read('src/pages/admin/AdminAcademyHub.tsx')
const landing=read('src/pages/public/AcademyLibraryLanding.tsx')
const routes=read('src/AppV2.tsx')
const publicLanding=read('src/pages/public/LandingPage.tsx')

test('Academy management opens first on content and retains all course tools',()=>{
 assert.match(routes,/AdminAcademyHub/)
 assert.match(hub,/useState<'library'\|'courses'>\(isAdmin\?'library':'courses'\)/)
 assert.match(hub,/AdminAcademyLibrary/)
 assert.match(hub,/AdminAcademy/)
 assert.match(hub,/role==='admin'/)
 assert.match(hub,/Gestão de conteúdo/)
 assert.match(admin,/＋ E-book/)
 assert.match(admin,/＋ Audiobook/)
})
test('library originals are confined to the private Drive and verified before being stored',()=>{
 assert.match(drive,/ensureAcademyLibraryFolder/)
 assert.match(drive,/academy-library-root/)
 assert.match(drive,/academy-library-release/)
 assert.match(uploader,/await requireUser\(request\)/)
 assert.match(uploader,/ctx\.role!=='admin'/)
 assert.match(uploader,/playMomentsKind:'academy-library-private'/)
 assert.match(uploader,/file\.parents\.includes\(folder\.folderId\)/)
 assert.match(uploader,/file\.appProperties\?\.playMomentsKind/)
 assert.match(uploader,/mimeType!==expectedType/)
 assert.match(uploader,/size>350\*1024\*1024/)
 assert.doesNotMatch(uploader,/anyone|type:'anyone'/)
 assert.match(api,/action:'confirm'/)
 assert.match(api,/action:'start'/)
})
test('new items create draft landing; legacy landing pages are untouched',()=>{
 assert.match(db,/after insert on public\.academy_library_items/)
 assert.match(db,/for each row execute function public\.academy_library_create_landing_on_insert/)
 assert.match(db,/\b'draft'\b/)
 assert.match(db,/landing_page_id uuid references public\.site_landing_pages/)
 assert.doesNotMatch(db,/update public\.academy_library_items\s+set landing_page_id.*where landing_page_id is null/)
 assert.match(db,/after update of status on public\.academy_library_items/)
 assert.match(db,/NEW\.status is distinct from OLD\.status/)
 assert.match(admin,/A landing é criada em rascunho/)
 assert.match(admin,/\/admin\/landings\?edit=/)
})
test('customer grants are per item, revocable and access is private',()=>{
 assert.match(api,/from\('academy_library_grants'\)/)
 assert.match(api,/onConflict:'item_id,user_id'/)
 assert.match(api,/active,source:'admin'/)
 assert.match(admin,/Liberar acesso/)
 assert.match(admin,/Revogar/)
 assert.match(admin,/A concessão é por formato/)
})
test('public landing never exposes private Drive file IDs, temporary tickets or customer names',()=>{
 assert.match(db,/public\.academy_public_library_landing\(p_slug text\)/)
 assert.match(db,/grant execute on function public\.academy_public_library_landing\(text\) to anon,authenticated/)
 assert.match(db,/i\.status='published'/)
 assert.doesNotMatch(db,/returns table\([\s\S]*?drive_file_id/)
 assert.match(landing,/academy_public_library_landing/)
 assert.match(landing,/A criação de conta é gratuita/)
 assert.match(landing,/depende de liberação/)
 assert.match(publicLanding,/startsWith\('biblioteca-'\)/)
 assert.doesNotMatch(landing,/drive_file_id|access_token/)
})
test('book and audiobook variants have different editing fields and media formats',()=>{
 assert.match(admin,/format==='ebook'/)
 assert.match(admin,/Trecho gratuito para a landing/)
 assert.match(admin,/URL de amostra pública do áudio/)
 assert.match(admin,/Capa da obra/)
 assert.match(admin,/Banner da landing/)
 assert.match(api,/format==='ebook'\?'application\/pdf':'audio\/mpeg'/)
})
