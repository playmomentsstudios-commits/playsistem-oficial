import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
import test from 'node:test'
const sql=readFileSync(new URL('../supabase/migrations/20261011013000_wa_relevant_task_files_and_human_updates.sql',import.meta.url),'utf8')

test('customer-friendly titles reflect real stage/task status, not generic platform title',()=>{
  assert.match(sql,/✨ \*Seu projeto deu mais um passo!\*/)
  assert.match(sql,/✅ \*Mais uma entrega concluída!\*/)
  assert.match(sql,/🚀 \*Estamos avançando na sua entrega!\*/)
  assert.match(sql,/when 'review'/)
  assert.match(sql,/when 'completed'/)
  assert.match(sql,/when 'changes_requested'/)
  assert.doesNotMatch(sql,/SAGAMENTE — Tarefa atualizada/)
})
test('task messages include distinct authorized files, not only the newest file',()=>{
  assert.match(sql,/for f in/)
  assert.match(sql,/n.type='project_task' and c.task_id=v_task/)
  assert.match(sql,/v_main>=6/)
  assert.match(sql,/v_support>=2/)
  assert.match(sql,/v_file_name/)
  assert.match(sql,/candidate|client_visible/)
  assert.match(sql,/v_body:=v_body\|\|E'\\n\\n'\|\|v_group/)
  assert.match(sql,/📄 Apoio:/)
  assert.match(sql,/row_number\(\) over\(partition by coalesce\(e.version_group_id,e.id\)/)
  assert.match(sql,/order by is_support asc/)
})
test('file grouping respects client visibility and project task/stage relations',()=>{
  assert.match(sql,/c.project_id=v_project/)
  assert.match(sql,/c.client_visible/)
  assert.match(sql,/c.storage_provider='google_drive'/)
  assert.match(sql,/c.drive_file_id is not null/)
  assert.match(sql,/t.client_visible/)
  assert.match(sql,/s.client_visible/)
  assert.match(sql,/c.stage_id=t.stage_id/)
  assert.match(sql,/n.type='project_stage'/)
  assert.match(sql,/t.stage_id=v_stage/)
  assert.match(sql,/c.id=\(n.metadata->>'file_id'\)::uuid/)
  assert.match(sql,/p.project_type<>'internal'/)
  assert.match(sql,/project_customer_access/)
})
test('each file gets a separate 48h private token; task link comes last',()=>{
  assert.match(sql,/insert into public.wa_file_message_links/)
  assert.match(sql,/sha256\(convert_to\(v_token,'UTF8'\)\)/)
  assert.match(sql,/whatsapp-file-open\?t=/)
  assert.match(sql,/v_label\|\|E'\\n'\|\|v_link/)
  assert.match(sql,/Links dos arquivos válidos por 48 horas/)
  assert.match(sql,/^\/n\/\[A-Za-z0-9_-\]\{22\}/)
  assert.match(sql,/new.target_link/)
  assert.match(sql,/update public.whatsapp_message_outbox/)
  assert.match(sql,/return new;/)
})
test('no auto-send, no mutation of old messages or public Drive permission',()=>{
  assert.doesNotMatch(sql,/update public\.whatsapp_message_outbox.*?where created_at/s)
  assert.doesNotMatch(sql,/wa_bridge_auto_enabled\s*=\s*true/)
  assert.doesNotMatch(sql,/anyoneWithLink|permissions\.create|public-sharing\s*=\s*true/)
  assert.match(sql,/new.source<>'live'/)
  assert.match(sql,/new.status not in \('ready_manual','missing_phone'\)/)
})
