import test from 'node:test'
import assert from 'node:assert/strict'
import {readFileSync} from 'node:fs'
const read=path=>readFileSync(new URL('../'+path,import.meta.url),'utf8')
const helper=read('src/lib/projectFileOrganization.ts')
const admin=read('src/pages/admin/AdminProjectDetailV2.tsx')
const client=read('src/pages/customer/ProjectsPage.tsx')
const stage=read('src/pages/customer/ProjectStagePage.tsx')
const api=read('src/api/portal.ts')
const sync=read('supabase/functions/google-drive-project-sync/index.ts')

test('admin represents physical Drive folders with their actual registered IDs',()=>{
 for(const name of ['received','raw','production','preview','approved','delivery'])
   assert.match(helper,new RegExp("kind:'"+name+"'"))
 assert.match(helper,/folder\.drive_folder_id/)
 assert.match(helper,/byId\.set\(registered\.drive_folder_id,item\)/)
 assert.match(helper,/byId\.set\(folder\.drive_folder_id,item\)/)
 assert.match(helper,/Outras subpastas do Drive/)
 assert.match(helper,/Raiz do projeto/)
 assert.match(admin,/adminProjectFolderGroups\(files,folderDirectory\.standard,folderDirectory\.custom,folderDirectory\.stages,project\.drive_folder_id\)/)
 assert.match(admin,/group\.files\.map\(file=>/)
 assert.match(admin,/Pasta vazia/)
 assert.match(admin,/arquivos por pasta|Arquivos por pasta/i)
 assert.match(api,/projectDriveFolderDirectory: async/)
 assert.match(api,/from\('project_drive_folders'\)/)
 assert.match(api,/from\('project_custom_folders'\)/)
 assert.match(api,/from\('project_stage_drive_folders'\)/)
})

test('moving a file changes its physical Drive folder but preserves the task/stage/visibility',()=>{
 assert.match(admin,/fileManagementApi\.moveToCustom\(file\.id,folder\.id\)/)
 assert.match(admin,/fileManagementApi\.move\(file\.id,destination\)/)
 assert.match(admin,/A etapa, tarefa e visibilidade serão preservadas/)
 assert.match(admin,/movingFile===file\.id/)
 assert.match(admin,/if\(!window\.confirm/)
 assert.match(admin,/folderDirectory\.custom/)
 assert.match(admin,/folderDirectory\.standard/)
 assert.match(admin,/assignClientFileTask/)
 assert.match(admin,/assignClientFileStage/)
})

test('Google inventory sync preserves stage metadata on existing files',()=>{
 assert.match(sync,/if \(key === "stage_id"\) continue/)
 assert.match(sync,/stage_id: folder\.stageId/)
 assert.match(sync,/client_visible: false/)
 assert.match(sync,/const matched = known\.get\(entry\.id\)/)
 assert.doesNotMatch(sync,/\.delete\(\)/)
})

test('customer sees only published deliverables grouped by allowed stages and tasks',()=>{
 assert.match(helper,/if\(!file\.client_visible\)continue/)
 assert.match(helper,/if\(file\.task_id&&!task\)continue/)
 assert.match(helper,/if\(stageId&&!stage\)continue/)
 assert.match(helper,/Materiais gerais do projeto/)
 assert.match(helper,/task\?task\.title:stage\?stage\.name/)
 assert.match(helper,/description:task&&stage\?'Etapa: '/)
 assert.match(client,/customerProjectFileGroups\(files,stages,tasks\)/)
 assert.match(client,/fileGroups\.flatMap\(group=>group\.files\)/)
 assert.match(client,/group\.title/)
 assert.match(client,/group\.description/)
 assert.match(client,/group\.files\.map\(\(file:any\)=>/)
 assert.doesNotMatch(client,/drive_folder_id.*\<Link/)
 assert.match(stage,/customerProjectFileGroups\(files/)
 assert.match(stage,/group\.stageId===stageId/)
})
